export const isKorean = navigator.language.toLowerCase().startsWith("ko");
export const t = isKorean ? ko : en;

export function errorText(code: unknown): string {
  switch (code) {
    case "unsupported":
      return t.unsupported;
    case "not_found":
      return t.notFound;
    case "no_images":
      return t.noImages;
    default:
      return t.loadFailed;
  }
}
